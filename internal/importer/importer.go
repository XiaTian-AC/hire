// Package importer converts justfiles, Makefiles and go-task
// Taskfile.yml files into the pure-static hire Taskfile.toml schema.
// Everything the schema cannot express is either kept verbatim in the
// output or skipped, and each such feature is reported as exactly one
// "hire: not migrated:" warning line so nothing disappears silently.
package importer

import (
	"fmt"
	"path/filepath"
	"regexp"
	"strings"
)

// Task is one imported task in the hire schema.
type Task struct {
	Name string
	Desc string
	Cmds []string
	Deps []string
	Args []Arg
	OS   []string // when.os; one entry is emitted as a scalar
}

// Arg is one declared task argument.
type Arg struct {
	Name     string
	Type     string // "string" | "bool" | "num"
	Required bool
	Desc     string
}

// Result is a conversion outcome: tasks in source order plus the
// warning lines for stderr, verbatim and in order.
type Result struct {
	Tasks    []Task
	Warnings []string
}

// warnf appends one complete warning line; the caller prints them as-is.
func warnf(w *[]string, format string, args ...any) {
	*w = append(*w, "hire: not migrated: "+fmt.Sprintf(format, args...))
}

// Import converts src, a file of the given format ("just", "make" or
// "task"; see Sniff), into the hire schema.
func Import(from, path string, src []byte) (*Result, error) {
	switch from {
	case "just":
		return parseJust(path, src)
	case "make":
		return parseMake(path, src)
	case "task":
		return parseGoTask(path, src)
	}
	return nil, fmt.Errorf("unknown source format %q (use: just, make, task)", from)
}

// justSigRe matches a just recipe header at column 0: optional @, a
// name, the parameter list BEFORE the colon, then the dependency list
// AFTER the colon (just syntax: `test TEST: build`). A colon directly
// followed by `=` is the `:=` assignment operator, so callers must
// reject signature matches whose dependency group starts with `=`.
var justSigRe = regexp.MustCompile(`^(@?)([a-zA-Z_][a-zA-Z0-9_-]*)(.*?)\s*:\s*([^#]*)$`)

// Sniff detects the source format. The file name decides first; then
// content: a leading version:/tasks: line means go-task, tab-prefixed
// recipe lines mean make, recipe headers with colons and no tab
// structure mean just. Anything else is ambiguous.
func Sniff(path string, src []byte) (string, error) {
	switch strings.ToLower(filepath.Base(path)) {
	case "justfile", ".justfile":
		return "just", nil
	case "makefile", "gnumakefile":
		return "make", nil
	case "taskfile.yml", "taskfile.yaml":
		return "task", nil
	}
	lines := strings.Split(string(src), "\n")
	tabRecipe, justRecipe := false, false
	for _, ln := range lines {
		ln = strings.TrimSuffix(ln, "\r")
		if strings.HasPrefix(ln, "\t") && strings.TrimSpace(ln) != "" {
			tabRecipe = true
		}
		if justSigRe.MatchString(ln) {
			justRecipe = true
		}
	}
	// go-task marker: first meaningful line is a top-level mapping key.
	for _, ln := range lines {
		t := strings.TrimSpace(strings.TrimSuffix(ln, "\r"))
		if t == "" || t == "---" || strings.HasPrefix(t, "#") {
			continue
		}
		if strings.HasPrefix(t, "version:") || strings.HasPrefix(t, "tasks:") {
			return "task", nil
		}
		break
	}
	if tabRecipe {
		return "make", nil
	}
	if justRecipe {
		return "just", nil
	}
	return "", fmt.Errorf("cannot determine the format of %q; use --from just, --from make or --from task", filepath.Base(path))
}

// Emit renders the result as a hire Taskfile.toml. Inside each task
// all scalar and array keys (desc, cmds, deps, when) are written
// BEFORE any [tasks.x.args.*] sub-table header: keys that follow a
// sub-table header belong to that sub-table, so they must never trail
// args (the key-order trap the Task 2 review flagged).
func Emit(r *Result, source string) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by `hire import` from %s\n", filepath.Base(source))
	fmt.Fprintln(&b, "# every 'hire: not migrated' warning from the conversion marks a feature you must port by hand")
	for _, t := range r.Tasks {
		fmt.Fprintf(&b, "\n[tasks.%s]\n", tomlKey(t.Name))
		if t.Desc != "" {
			fmt.Fprintf(&b, "desc = %s\n", tomlStr(t.Desc))
		}
		if len(t.Cmds) == 1 {
			fmt.Fprintf(&b, "cmd = %s\n", tomlStr(t.Cmds[0]))
		} else {
			b.WriteString("cmds = [")
			for i, c := range t.Cmds {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(tomlStr(c))
			}
			b.WriteString("]\n")
		}
		if len(t.Deps) > 0 {
			parts := make([]string, len(t.Deps))
			for i, d := range t.Deps {
				parts[i] = tomlStr(d)
			}
			fmt.Fprintf(&b, "deps = [%s]\n", strings.Join(parts, ", "))
		}
		switch len(t.OS) {
		case 0:
		case 1:
			fmt.Fprintf(&b, "when = { os = %s }\n", tomlStr(t.OS[0]))
		default:
			parts := make([]string, len(t.OS))
			for i, o := range t.OS {
				parts[i] = tomlStr(o)
			}
			fmt.Fprintf(&b, "when = { os = [%s] }\n", strings.Join(parts, ", "))
		}
		for _, a := range t.Args {
			fmt.Fprintf(&b, "[tasks.%s.args.%s]\n", tomlKey(t.Name), tomlKey(a.Name))
			if a.Type != "" && a.Type != "string" {
				fmt.Fprintf(&b, "type = %s\n", tomlStr(a.Type))
			}
			if a.Required {
				b.WriteString("required = true\n")
			}
			if a.Desc != "" {
				fmt.Fprintf(&b, "desc = %s\n", tomlStr(a.Desc))
			}
		}
	}
	return []byte(b.String())
}

var bareKeyRe = regexp.MustCompile(`^[A-Za-z0-9_-]+$`)

// tomlKey quotes a table key unless it is a legal bare key (make
// targets may contain dots or other characters that would nest or
// break a bare table header).
func tomlKey(s string) string {
	if bareKeyRe.MatchString(s) {
		return s
	}
	return tomlStr(s)
}

// tomlStr renders s as a TOML basic string using only escapes TOML
// defines (\b \t \n \f \r \" \\ \uXXXX); quotes, backslashes and
// non-ASCII text like 中文 pass through safely.
func tomlStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
